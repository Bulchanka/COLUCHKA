const normalizeText = (value: string) => value.toLocaleLowerCase("ru-RU").replaceAll("ё", "е").replace(/[«»"']/g, "").replace(/\s+/g, " ").trim();
const escaped = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replaceAll(" ", "\\s+");

function hasNegation(text: string, phrase: string) {
  const index = text.indexOf(phrase);
  if (index < 0) return false;
  const before = text.slice(Math.max(0, index - 28), index);
  const after = text.slice(index + phrase.length, index + phrase.length + 18);
  return /(?:нет|не было|без|отрицаю|отсутствует)\s*$/.test(before) || /^\s*(?:нет|не было|отсутствует)(?:\s|$)/.test(after);
}

function findPhrase(text: string, phrases: string[]) {
  return phrases.find((phrase) => new RegExp(`(?:^|\\s)${escaped(normalizeText(phrase))}(?=\\s|$|[,.!?;:])`, "i").test(text));
}

export function normalizePatientText(input: string): SymptomNormalization {
  const text = normalizeText(input);
  const facts: NormalizedFact[] = [];
  const addRule = (candidate: Rule) => {
    const phrase = findPhrase(text, candidate.phrases);
    if (!phrase || facts.some((item) => item.code === candidate.code)) return;
    const status = hasNegation(text, normalizeText(phrase)) ? "denied" : "present";
    facts.push({
      code: candidate.code,
      category: candidate.category,
      normalized: candidate.normalized,
      phrase,
      status,
      clarification: status === "present" ? candidate.clarification : undefined,
      redFlag: status === "present" ? candidate.redFlag : undefined,
    });
  };
  RULES.forEach(addRule);
  AMBIGUOUS.forEach((candidate) => {
    // Точный бытовой термин сохраняем как неоднозначный, пока пациент его не уточнил.
    const phrase = findPhrase(text, candidate.phrases);
    const alreadyResolved =
      candidate.code === "AMB-NOT-BREATHING" &&
      facts.some((item) => item.code === "N01" || item.code === "D01" || item.code === "D02" || item.code === "D03" || item.code === "D06");
    if (phrase && !alreadyResolved && !facts.some((item) => item.phrase === phrase)) addRule(candidate);
  });

  for (const item of RED_FLAG_ONLY) {
    if (text.includes(normalizeText(item.phrase))) {
      facts.push({ code: "RED-FLAG", category: "срочность", normalized: item.label, phrase: item.phrase, status: "present", redFlag: item.label });
    }
  }

  const redFlags = [...new Set(facts.filter((fact) => fact.status === "present" && fact.redFlag).map((fact) => fact.redFlag as string))];
  const clarifications = [...new Set(facts.filter((fact) => fact.status === "present" && fact.clarification).map((fact) => fact.clarification as string))];
  return {
    facts,
    normalizedSymptoms: [...new Set(facts.filter((fact) => fact.status === "present" && fact.category !== "неоднозначное" && fact.category !== "срочность").map((fact) => fact.normalized))],
    clarifications,
    redFlags,
    hasRedFlag: redFlags.length > 0,
    dictionarySource: "slovar_normalizacii_simptomov_kolyuchka.txt",
  };
}
