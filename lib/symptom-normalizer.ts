export type PatientFactStatus = "present" | "denied";

export type NormalizedFact = {
  code: string;
  category: string;
  normalized: string;
  phrase: string;
  status: PatientFactStatus;
  clarification?: string;
  redFlag?: string;
};

export type SymptomNormalization = {
  facts: NormalizedFact[];
  normalizedSymptoms: string[];
  clarifications: string[];
  redFlags: string[];
  hasRedFlag: boolean;
  dictionarySource: string;
};

type Rule = {
  code: string;
  category: string;
  normalized: string;
  phrases: string[];
  clarification?: string;
  redFlag?: string;
};

const rule = (
  code: string,
  category: string,
  normalized: string,
  phrases: string[],
  options: Pick<Rule, "clarification" | "redFlag"> = {}
): Rule => ({ code, category, normalized, phrases, ...options });

